import { expect, test } from '@playwright/test';

test('writer creates, edits, cancels, and reloads a post', async ({ page }) => {
  const browserErrors = [];
  page.on('console', (message) => { if (message.type() === 'error') browserErrors.push(message.text()); });
  page.on('pageerror', (error) => browserErrors.push(error.message));
  await page.goto('/');
  await page.getByRole('link', { name: 'Get Started' }).click();
  await page.getByLabel('Display Name').fill('Mira Chen');
  await page.getByLabel('Username').fill('mira');
  await page.getByLabel('Password').fill('local-pass');
  await page.getByLabel('Confirm Password').fill('local-pass');
  await page.getByRole('button', { name: 'Create Account' }).click();
  await expect(page).toHaveURL(/\/blogs$/);
  await page.getByRole('link', { name: 'Write your first post' }).click();
  await expect(page.getByRole('heading', { name: 'Write a Post' })).toBeVisible();
  await page.getByRole('button', { name: 'Save Post' }).click();
  await expect(page.getByText('Title is required.')).toBeVisible();
  await expect(page.getByText('Content is required.')).toBeVisible();
  await page.getByLabel('Title').fill('A small idea');
  await page.getByLabel('Content').fill('A thought worth sharing with the community.');
  await expect(page.getByRole('status')).toHaveText('41 characters');
  await page.getByRole('button', { name: 'Save Post' }).click();
  await expect(page.getByRole('heading', { name: 'A small idea' })).toBeVisible();
  await expect(page.getByText('A thought worth sharing with the community.')).toBeVisible();
  const savedPost = await page.evaluate(() => JSON.parse(localStorage.getItem('writespace_posts'))[0]);
  const session = await page.evaluate(() => JSON.parse(localStorage.getItem('writespace_session')));
  expect(savedPost).toMatchObject({ title: 'A small idea', authorId: session.userId, authorName: 'Mira Chen' });
  await page.getByRole('link', { name: 'Edit' }).click();
  await expect(page.getByLabel('Title')).toHaveValue('A small idea');
  await page.getByLabel('Title').fill('A revised idea');
  await page.getByRole('link', { name: 'Cancel' }).click();
  await expect(page.getByRole('heading', { name: 'A small idea' })).toBeVisible();
  await page.getByRole('link', { name: 'Edit' }).click();
  await page.getByLabel('Title').fill('A revised idea');
  await page.getByRole('button', { name: 'Save Changes' }).click();
  await expect(page.getByRole('heading', { name: 'A revised idea' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'A revised idea' })).toBeVisible();
  await expect(page.getByText('A thought worth sharing with the community.')).toBeVisible();
  await page.screenshot({ path: 'test-results/post-reader-after-edit.png', fullPage: true });
  expect(browserErrors).toEqual([]);
});
