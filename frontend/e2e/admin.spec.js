import { expect, test } from '@playwright/test';

test.beforeEach(async ({ page }) => {
  await page.goto('/');
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
});

test('administrator reviews dashboard and manages accounts safely', async ({ page }) => {
  const browserErrors = [];
  page.on('console', (message) => { if (message.type() === 'error') browserErrors.push(message.text()); });
  page.on('pageerror', (error) => browserErrors.push(error.message));
  await page.goto('/');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Login' }).click();
  await page.getByLabel('Username').fill('admin');
  await page.getByLabel('Password').fill('admin');
  await page.getByRole('button', { name: 'Login' }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await expect(page.getByRole('heading', { name: 'A clear view of your community.' })).toBeVisible();
  await expect(page.getByText('Total Posts')).toBeVisible();
  await expect(page.getByText('Total Users', { exact: true })).toBeVisible();
  await expect(page.getByText('Total Admins')).toBeVisible();
  await expect(page.getByText('Total users', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Manage Users' }).click();
  await expect(page.getByRole('heading', { name: 'User Management' })).toBeVisible();
  await expect(page.getByText('0 registered accounts')).toBeVisible();
  await expect(page.getByText('No registered accounts yet. Create the first account above.')).toBeVisible();
  await page.getByRole('button', { name: 'Create Account' }).click();
  await expect(page.getByText('Display name is required.')).toBeVisible();
  await expect(page.getByText('Username is required.')).toBeVisible();
  await expect(page.getByText('Password is required.')).toBeVisible();
  await expect(page.getByLabel('Display Name')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByLabel('Username')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByLabel('Password')).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('Display Name').fill('Ari Kim');
  await page.getByLabel('Username').fill('ari');
  await page.getByLabel('Password').fill('local-pass');
  await page.getByLabel('Role').selectOption('user');
  await page.getByRole('button', { name: 'Create Account' }).click();
  await expect(page.getByText('Ari Kim')).toHaveCount(2);
  await expect(page.getByText('ari', { exact: true })).toHaveCount(2);
  await expect(page.getByText('User', { exact: true })).toHaveCount(3);
  await expect(page.getByRole('button', { name: 'Default admin cannot be deleted.' })).toBeDisabled();
  const ariRow = page.getByRole('row', { name: /Ari Kim ari User/ });
  page.once('dialog', (dialog) => dialog.dismiss());
  await ariRow.getByRole('button', { name: 'Delete Ari Kim' }).click();
  await expect(ariRow).toBeVisible();
  page.once('dialog', (dialog) => dialog.accept());
  await ariRow.getByRole('button', { name: 'Delete Ari Kim' }).click();
  await expect(ariRow).toHaveCount(0);
  await page.getByRole('button', { name: 'Logout' }).first().click();
  await expect(page).toHaveURL('/');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Get Started' }).click();
  await page.getByLabel('Display Name').fill('Mira Chen');
  await page.getByLabel('Username').fill('mira');
  await page.getByLabel('Password', { exact: true }).fill('local-pass');
  await page.getByLabel('Confirm Password').fill('local-pass');
  await page.getByRole('button', { name: 'Create Account' }).click();
  await expect(page).toHaveURL(/\/blogs$/);
  await page.getByRole('link', { name: 'WriteSpace home' }).click();
  await expect(page).toHaveURL('/');
  await page.screenshot({ path: 'test-results/admin-role-boundary.png', fullPage: true });
  expect(browserErrors).toEqual([]);
});